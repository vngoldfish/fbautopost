    def test_post_accounts_single_target_high_concurrency_upsert(self):
        """
        Adversarial Challenge: 30 concurrent threads simultaneously POST /api/accounts
        with the EXACT same targetId, each attempting to write differing tokens and names.
        Validates:
        1. Zero 500 Internal Server Errors (No unhandled sqlite3.IntegrityError: UNIQUE constraint failed: accounts.target_id)
        2. Every request returns HTTP 200 with success=True
        3. Exactly ONE record exists in the database for that targetId
        4. The record's original primary key (id) and created_at remain stable (immutability under upsert)
        5. The final record has updated dynamic values and updated_at >= created_at
        """
        thread_count = 30
        barrier = threading.Barrier(thread_count)
        shared_target_id = f"target_fb_{int(time.time() * 1000)}_{uuid.uuid4().hex[:4]}"

        # Seed valid workers in the database so foreign key constraints are satisfied
        for wid in ["worker_0", "worker_1", "worker_2"]:
            execute_write(
                "INSERT INTO workers (id, name, status, last_heartbeat, created_at, updated_at) "
                "VALUES (?, ?, 'idle', ?, ?, ?) ON CONFLICT(id) DO NOTHING",
                (wid, f"Test Node {wid}", int(time.time() * 1000), int(time.time() * 1000), int(time.time() * 1000))
            )

        status_codes: List[int] = []
        response_bodies: List[Dict[str, Any]] = []
        errors: List[Exception] = []
        lock = threading.Lock()

        def worker(thread_idx: int):
            try:
                barrier.wait(timeout=10.0)
                payload = {
                    "name": f"Account Version {thread_idx}",
                    "accessToken": f"EAAB_token_worker_{thread_idx}",
                    "targetId": shared_target_id,
                    "type": "profile",
                    "projectKey": "all",
                    "workerId": f"worker_{thread_idx % 3}"
                }
                res = client.post("/api/accounts", json=payload)
                with lock:
                    status_codes.append(res.status_code)
                    if res.headers.get("content-type", "").startswith("application/json"):
                        response_bodies.append(res.json())
                    else:
                        response_bodies.append({"raw": res.text})
            except Exception as e:
                with lock:
                    errors.append(e)

        threads = [threading.Thread(target=worker, args=(i,)) for i in range(thread_count)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=20.0)

        # Query database state
        saved_accounts = query_all("SELECT * FROM accounts WHERE target_id = ?", (shared_target_id,))

        # Cleanup
        execute_write("DELETE FROM accounts WHERE target_id = ?", (shared_target_id,))
        execute_write("DELETE FROM logs WHERE entity_id IN (SELECT id FROM accounts WHERE target_id = ?)", (shared_target_id,))
        execute_write("DELETE FROM workers WHERE id IN ('worker_0', 'worker_1', 'worker_2')")

        # 1. Zero exceptions raised
        assert len(errors) == 0, f"Worker threads encountered unexpected client exceptions: {errors}"

        # 2. Check all status codes are 200 or 201
        non_success = [code for code in status_codes if code not in [200, 201]]
        assert len(non_success) == 0, (
            f"Detected non-success responses under concurrent upsert: {non_success}. "
            f"Sample responses: {response_bodies[:3]}"
        )

        # 3. Check every response body indicated success
        failed_bodies = [b for b in response_bodies if not b.get("success")]
        assert len(failed_bodies) == 0, f"Responses failed: {failed_bodies}"

        # 4. Exactly 1 record must exist in the database (no duplicate rows inserted)
        assert len(saved_accounts) == 1, (
            f"Expected exactly 1 account record for targetId {shared_target_id}, but found {len(saved_accounts)}"
        )

        record = saved_accounts[0]
        # 5. Check integrity of stored account fields
        assert record["target_id"] == shared_target_id
        assert record["status"] == "active"
        assert record["cookie_status"] == "valid"
        assert record["updated_at"] >= record["created_at"]
        assert record["name"].startswith("Account Version")
        assert record["access_token"].startswith("EAAB_token_worker_")

    def test_post_accounts_multi_target_mixed_concurrent_upsert(self):
        """
        Adversarial Challenge: 40 threads partitioned across 4 distinct target IDs
        (10 threads per target ID) all firing simultaneously.
        Verifies:
        1. All 4 targets survive high-load contention without lockups or 500s.
        2. Exactly 4 rows exist in the database (one per target ID).
        3. No cross-talk or data contamination between targets.
        """
        targets = [f"multi_target_{i}_{int(time.time() * 1000)}" for i in range(4)]
        threads_per_target = 10
        total_threads = len(targets) * threads_per_target
        barrier = threading.Barrier(total_threads)

        status_codes = []
        errors = []
        lock = threading.Lock()

        def worker(target_id: str, idx: int):
            try:
                barrier.wait(timeout=10.0)
                payload = {
                    "name": f"User {target_id}_{idx}",
                    "accessToken": f"token_{target_id}_{idx}",
                    "targetId": target_id,
                    "type": "page"
                }
                res = client.post("/api/accounts", json=payload)
                with lock:
                    status_codes.append(res.status_code)
            except Exception as e:
                with lock:
                    errors.append(e)

        threads = []
        for target_id in targets:
            for idx in range(threads_per_target):
                threads.append(threading.Thread(target=worker, args=(target_id, idx)))

        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=25.0)

        # Query database counts
        db_rows = query_all("SELECT * FROM accounts WHERE target_id IN (?, ?, ?, ?)", tuple(targets))

        # Cleanup
        for target_id in targets:
            execute_write("DELETE FROM accounts WHERE target_id = ?", (target_id,))

        assert len(errors) == 0, f"Exceptions occurred: {errors}"
        assert all(code in [200, 201] for code in status_codes), f"Status code failures: {status_codes}"
        assert len(db_rows) == 4, f"Expected 4 distinct account rows, got {len(db_rows)}"

        retrieved_targets = {row["target_id"] for row in db_rows}
        assert retrieved_targets == set(targets), f"Missing target IDs: {set(targets) - retrieved_targets}"

