    def test_concurrent_account_upsert_and_health_transition(self):
        """
        Adversarial Challenge: Interleaved execution of POST /api/accounts (upsert)
        and POST /api/accounts/{account_id}/health (status update) across 20 threads.
        Verifies:
        1. No deadlocks between accounts router endpoints.
        2. Account status updates cleanly transition without database lock errors.
        """
        account_target = f"health_stress_{int(time.time() * 1000)}"
        
        # Seed the account first
        seed_res = client.post("/api/accounts", json={
            "name": "Health Test Account",
            "accessToken": "seed_token",
            "targetId": account_target,
            "type": "page"
        })
        assert seed_res.status_code in [200, 201]
        account_id = seed_res.json()["account"]["id"]

        thread_count = 20
        barrier = threading.Barrier(thread_count)
        statuses = ["healthy", "checkpoint", "logged_out", "expired"]
        results = []
        lock = threading.Lock()

        def worker(idx: int):
            try:
                barrier.wait(timeout=5.0)
                if idx % 2 == 0:
                    # Upsert worker
                    res = client.post("/api/accounts", json={
                        "name": f"Interleaved Name {idx}",
                        "accessToken": f"token_int_{idx}",
                        "targetId": account_target,
                        "type": "page"
                    })
                    with lock:
                        results.append(("upsert", res.status_code))
                else:
                    # Health worker
                    chosen_status = statuses[idx % len(statuses)]
                    res = client.post(f"/api/accounts/{account_id}/health", json={
                        "healthStatus": chosen_status
                    })
                    with lock:
                        results.append(("health", res.status_code))
            except Exception as e:
                with lock:
                    results.append(("error", str(e)))

        threads = [threading.Thread(target=worker, args=(i,)) for i in range(thread_count)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=15.0)

        # Cleanup
        execute_write("DELETE FROM accounts WHERE target_id = ?", (account_target,))
        execute_write("DELETE FROM logs WHERE entity_id = ?", (account_id,))

        # Verify all operations succeeded with HTTP 200 or 201
        failed_ops = [r for r in results if r[1] not in [200, 201]]
        assert len(failed_ops) == 0, f"Interleaved operations had failures: {failed_ops}"

    def test_add_activity_log_100_threads_saturation(self):
        """
        Adversarial Challenge: 100 concurrent threads executing 20 writes each (2000 total writes).
        Tests whether the 6-hex-char entropy space (16,777,216 values per ms) ever experiences
        a birthday attack collision under heavy thread saturation.
        """
        num_threads = 100
        writes_per_thread = 20
        total_expected = num_threads * writes_per_thread
        barrier = threading.Barrier(num_threads)

        errors = []
        captured_ids = []
