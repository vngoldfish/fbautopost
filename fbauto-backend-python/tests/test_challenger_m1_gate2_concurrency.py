    def test_add_activity_log_massive_concurrency_blast(self):
        """
        Adversarial Challenge: 50 concurrent threads simultaneously blasting add_activity_log.
        Each thread executes 30 rapid log operations (1500 total operations) without delay.
        Validates:
        1. Zero primary key collisions (sqlite3.IntegrityError: UNIQUE constraint failed: logs.id)
        2. Zero lock timeouts (OperationalError: database is locked)
        3. All generated log IDs are unique (100% distinct set)
        4. Every log ID adheres to the format 'log_{now_ms}_{entropy}' where entropy is 6 hex chars
        5. Database record count matches exactly 1500 rows
        """
        num_threads = 50
        writes_per_thread = 30
        total_expected_logs = num_threads * writes_per_thread
        barrier = threading.Barrier(num_threads)

        errors: List[Exception] = []
        captured_ids: List[str] = []
        lock = threading.Lock()

        test_tag = f"gate2_blast_{int(time.time() * 1000)}_{uuid.uuid4().hex[:4]}"

        def worker(thread_idx: int):
            try:
                barrier.wait(timeout=10.0)
                local_ids = []
                for i in range(writes_per_thread):
                    log_id = add_activity_log(
                        action="CHALLENGER_GATE2_STRESS",
                        entity_type="thread_worker",
                        entity_id=f"t_{thread_idx}_seq_{i}",
                        project_key="all",
                        details={"tag": test_tag, "thread": thread_idx, "iteration": i}
                    )
                    local_ids.append(log_id)
                with lock:
                    captured_ids.extend(local_ids)
            except Exception as e:
                with lock:
                    errors.append(e)
            finally:
                close_thread_connection()

        threads = [threading.Thread(target=worker, args=(i,)) for i in range(num_threads)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=30.0)

        # Query database for rows created during this test
        db_rows = query_all(
            "SELECT id, details FROM logs WHERE action = 'CHALLENGER_GATE2_STRESS' AND details LIKE ?",
            (f"%{test_tag}%",)
        )

        # Cleanup test data immediately
        execute_write(
            "DELETE FROM logs WHERE action = 'CHALLENGER_GATE2_STRESS' AND details LIKE ?",
            (f"%{test_tag}%",)
        )

        # 1. Check no worker raised an exception
        assert len(errors) == 0, f"add_activity_log crashed under 50-thread contention: {errors}"

        # 2. Check total logs generated by workers
        assert len(captured_ids) == total_expected_logs, (
            f"Expected {total_expected_logs} log IDs, but captured {len(captured_ids)}"
        )

        # 3. Check for zero duplicates in returned IDs
        unique_ids = set(captured_ids)
        assert len(unique_ids) == total_expected_logs, (
            f"Primary key collision detected! {total_expected_logs - len(unique_ids)} duplicate IDs found!"
        )

        # 4. Check ID structure matches regex: log_<timestamp>_<6 hex chars>
        log_pattern = re.compile(r"^log_\d+_[0-9a-f]{6}$")
        invalid_format_ids = [lid for lid in captured_ids if not log_pattern.match(lid)]
        assert len(invalid_format_ids) == 0, (
            f"Found IDs that do not follow log_<timestamp>_<entropy> format: {invalid_format_ids[:5]}"
        )

        # 5. Check database actually saved every single row
        assert len(db_rows) == total_expected_logs, (
            f"Database row count mismatch: Expected {total_expected_logs}, found {len(db_rows)} in sqlite table"
        )

